// Conventions and normalization of the Gaussian basis-set data layer.
//
// The reference values are ERKALE's, because parity with ERKALE is the point:
//   * Cartesian component order and index -- src/basis.cpp (GaussianShell
//     constructor) and getind() in src/mathf.cpp
//   * relative normalization              -- GaussianShell::normalize()
//   * real solid harmonics                -- calcYlm_coeff() in
//                                            src/solidharmonics.cpp
//   * function ordering (contraction-slowest) -- function_norms()

